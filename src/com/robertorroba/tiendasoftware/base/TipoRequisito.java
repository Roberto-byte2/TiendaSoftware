package com.robertorroba.tiendasoftware.base;

/**
 * Enumeración que define los tipos de requisitos técnicos
 * que puede necesitar un producto de software.
 *
 * RAM: memoria RAM necesaria.
 * ESPACIO: espacio de almacenamiento necesario.
 * NUCLEOS: número de núcleos de procesador necesarios.
 */
public enum TipoRequisito {
    RAM,
    ESPACIO,
    NUCLEOS
}
